import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {check} from "../scripts/check_dawn_editorial_lists.mjs";
const here=path.dirname(fileURLToPath(import.meta.url));
const original=JSON.parse(fs.readFileSync(path.join(here,"..","docs","dawn-library","editorial-booklist-studio.v1.json"),"utf8"));
const c=()=>structuredClone(original),err=d=>check(d).join("|");
test("valid independent editorial pitches",()=>assert.deepEqual(check(c()),[]));
test("no source-first",()=>{const d=c();d.editorialFirst=false;assert.match(err(d),/editorial-first/);});
test("human review required",()=>{const d=c();d.publicationGate="automatic";assert.match(err(d),/human publication/);});
test("a reader question required",()=>{const d=c();d.archetypes[0].question="";assert.match(err(d),/missing question/);});
test("negative selection required",()=>{const d=c();d.archetypes[0].redFlag="";assert.match(err(d),/missing redFlag/);});
test("cannot assert published concepts",()=>{const d=c();d.archetypes[0].status="published";assert.match(err(d),/unapproved editorial status/);});
test("no download links in the editorial pitch",()=>{const d=c();d.pilots[0].sample[0].downloadUrl="https://example.org";assert.match(err(d),/downloadUrl/);});
test("direct pastoral attribution mandatory",()=>{const d=c();d.pilots[0].sample[0].recommender="someone";assert.match(err(d),/unattributed/);});
test("no fake recommendation source",()=>{const d=c();d.pilots[2].sample[0].recommendationEvidence="fake";assert.match(err(d),/unverified attribution/);});
test("source access only after choice",()=>{const d=c();d.sourcePolicy.stage="before-editorial";assert.match(err(d),/source-first policy/);});
test("no duplicate archetypes",()=>{const d=c();d.archetypes[1].id=d.archetypes[0].id;assert.match(err(d),/duplicate archetype/);});
